def facet_count(scenario: Scenario) -> int:
    return max(1, len(scenario.facet_offsets))


def facet_name(index: int, facets: int) -> str:
    """The facet the index-th question of an axis joins: questions join the facets in turn."""
    return f"facet {index % facets}" if facets > 1 else "audit"


def audit_questionnaire(questions_per_axis: int, facets: int = 1) -> Questionnaire:
    compass = Compass(
        axes=AxisPair(
            x=Axis(name="x", negative="negative", positive="positive"),
            y=Axis(name="y", negative="negative", positive="positive"),
        )
    )
    questions = tuple(
        Question(
            id=QuestionId(f"{axis}-{index:02d}"),
            axis=axis,
            facet=facet_name(index, facets),
            statements=PolarityPair(negative="negative statement", positive="positive statement"),
        )
        for axis in AxisKey
        for index in range(questions_per_axis)
    )
    return Questionnaire(title="audit", compass=compass, scale=SCALE, questions=questions, author="audit")


def facet_offsets(scenario: Scenario) -> dict[str, int]:
    """Each facet's fixed offset in points, by facet name; the one facet of a scenario without offsets sits at 0."""
    if not scenario.facet_offsets:
        return {facet_name(0, 1): 0}
    return {
        facet_name(index, len(scenario.facet_offsets)): offset for index, offset in enumerate(scenario.facet_offsets)
    }


def model_spread(scenario: Scenario, model: ModelId) -> float:
    """The factor on the model's three spreads: 1 for the first model, the scenario's for the second."""
    return scenario.second_spread if model == MODELS[1] else 1.0


def integer_effect(shuffler: random.Random, sd: float) -> int:
    """A normal draw rounded half to even, so the distribution of effects stays symmetric around 0."""
    return round(shuffler.gauss(0.0, sd))


def first_option_shift(display_order: DisplayOrder, lean: int) -> int:
    """The displayed-rating change that moves `lean` points toward the first-listed choice."""
    match display_order:
        case DisplayOrder.ASCENDING:
            return -lean
        case DisplayOrder.DESCENDING:
            return lean


def displayed_reply(condition: Condition, content: int, lean: int) -> DisplayedRating:
    """The canonical `content` rating as the condition displays it, pulled toward the first-listed choice and clamped.

    Clamping happens in display coordinates, as a reply does; it is symmetric around the center either way."""
    shown = displayed_rating(SCALE, condition.numeric_mapping, CanonicalRating(content))
    pulled = shown + first_option_shift(condition.display_order, lean)
    return DisplayedRating(min(max(pulled, 1), len(LABELS)))


def rated(trial: Trial, condition: Condition, displayed: DisplayedRating) -> TrialRecord:
    """The trial answered with `displayed`, read back to the canonical scale as a reply is."""
    reading = RatingRead(
        kind=ReadingKind.RATING,
        canonical=canonical_rating(SCALE, condition.numeric_mapping, displayed),
        displayed=displayed,
        span=Span(start=0, end=1),
        rule=RuleId("simulated"),
        hedge=None,
    )
    outcome = Replied(kind=TrialOutcomeKind.REPLIED, reading=reading, host=None, served_model=None, fingerprint=None)
    return TrialRecord(trial=trial, outcome=outcome)


def audit_conditions(wordings: int) -> tuple[Condition, ...]:
    """Both layout factors at both levels, crossed with `wordings` instruction wordings when there are several."""
    factors: tuple[Factor, ...] = (
        DisplayOrderFactor(kind=FactorKind.DISPLAY_ORDER, levels=tuple(DisplayOrder)),
        NumericMappingFactor(kind=FactorKind.NUMERIC_MAPPING, levels=tuple(NumericMapping)),
    )
    if wordings > 1:
        levels = tuple(f"wording {number}" for number in range(1, wordings + 1))
        factors += (InstructionFactor(kind=FactorKind.INSTRUCTION, levels=levels),)
    return cross(factors, STANDARD_INSTRUCTION)


def wording_effects(shuffler: random.Random, sd: float, conditions: Sequence[Condition]) -> dict[str, int]:
    """One integer shift per wording asked, in rating points toward the positive pole."""
    return {wording: integer_effect(shuffler, sd) for wording in dict.fromkeys(c.instruction for c in conditions)}


def shared_question_sd(scenario: Scenario) -> float:
    """The spread of the question effect's component both models share."""
    return math.sqrt(scenario.question_correlation) * scenario.question_sd


def own_question_sd(scenario: Scenario, model: ModelId) -> float:
    """The spread of the question effect's component the model draws on its own, at its own scale use."""
    return math.sqrt(1 - scenario.question_correlation) * scenario.question_sd * model_spread(scenario, model)


def statement_lean(scenario: Scenario, polarity: Polarity) -> int:
    """The extra agreement the scenario gives a statement toward `polarity`: on the negative pole's alone."""
    return scenario.negative_statement_lean if polarity is Polarity.NEGATIVE else 0


def second_shift(scenario: Scenario, model: ModelId, shuffler: random.Random) -> int:
    """One point toward the positive pole on the second model's question, with the scenario's share."""
    if model != MODELS[1] or scenario.second_shift_share == 0:
        return 0
    return int(shuffler.random() < scenario.second_shift_share)


def simulate_records(scenario: Scenario, seed: int) -> tuple[TrialRecord, ...]:
    """Two models answering every question under every condition; every effect is a symmetric integer.

    A rating is the center, plus the question's stance, effect, and wording shifts toward the phrasing's pole, plus
    the statement's own slant and the scenario's lean toward agreeing with it, plus a repetition's noise, then the
    scenario's lean toward the first-listed choice. The shared wording shift and the shared part of each question
    effect are drawn once for both models; a model's own effects are drawn at its own scale use."""
    shuffler = random.Random(seed)
    conditions = audit_conditions(scenario.wordings)
    questionnaire = audit_questionnaire(scenario.questions_per_axis, facet_count(scenario))
    offsets = facet_offsets(scenario)
    shared_shift = wording_effects(shuffler, scenario.wording_sd, conditions)
    shared_effects = {
        question.id: integer_effect(shuffler, shared_question_sd(scenario)) for question in questionnaire.questions
    }
    records: list[TrialRecord] = []
    for model in MODELS:
        spread = model_spread(scenario, model)
        model_shift = wording_effects(shuffler, scenario.model_wording_sd, conditions)
        for question in questionnaire.questions:
            stance = scenario.position_points + offsets[question.facet] + second_shift(scenario, model, shuffler)
            question_effect = shared_effects[question.id] + integer_effect(shuffler, own_question_sd(scenario, model))
            question_shift = wording_effects(shuffler, scenario.question_wording_sd, conditions)
            for polarity in Polarity:
                slant = integer_effect(shuffler, scenario.statement_sd * spread) + statement_lean(scenario, polarity)
                for condition in conditions:
                    wording = condition.instruction
                    shift = shared_shift[wording] + model_shift[wording] + question_shift[wording]
                    for repetition in range(scenario.repetitions_per_condition):
                        noise = integer_effect(shuffler, scenario.repetition_sd * spread)
                        trial = Trial(
                            key=TrialKey(f"{model}/{question.id}/{polarity}/{condition.id}/{repetition}"),
                            model=model,
                            question=question.id,
                            polarity=polarity,
                            condition=condition.id,
                            repetition=repetition,
                            position=len(records),
                        )
                        content = CENTER_RATING + polarity * (stance + question_effect + shift) + slant + noise
                        if scenario.noise is NoiseKind.UNIFORM:
                            content = shuffler.randint(1, len(LABELS))
                        displayed = displayed_reply(condition, content, scenario.first_option_lean)
                        records.append(rated(trial, condition, displayed))
    return tuple(records)


def integer_pmf(sd: float) -> dict[int, float]:
    """The distribution of a normal draw with standard deviation `sd` rounded to an integer; a point mass at 0 sd."""
    if sd == 0:
        return {0: 1.0}
    normal = NormalDist(0.0, sd)
    reach = math.ceil(PMF_REACH * sd)
    masses = {value: normal.cdf(value + 0.5) - normal.cdf(value - 0.5) for value in range(-reach, reach + 1)}
    total = sum(masses.values())
    return {value: mass / total for value, mass in masses.items()}


def convolve(first: Mapping[int, float], second: Mapping[int, float]) -> dict[int, float]:
    """The distribution of the sum of two independent integer draws."""
    summed: dict[int, float] = {}
    for one, mass_one in first.items():
        for other, mass_other in second.items():
            summed[one + other] = summed.get(one + other, 0.0) + mass_one * mass_other
    return summed


def clamped_rating(content: int) -> CanonicalRating:
    return CanonicalRating(min(max(content, 1), len(LABELS)))


def expected_answer_value(
    stance: int,
    polarity: Polarity,
    lean: int,
    question: Mapping[int, float],
    slant: Mapping[int, float],
    noise: Mapping[int, float],
) -> float:
    """The expected answer value of a statement toward `polarity`, over the question, slant, and noise draws."""
    return sum(
        mass_q
        * mass_s
        * mass_n
        * normalize(SCALE, clamped_rating(CENTER_RATING + polarity * (stance + q) + s + lean + n))
        * polarity
        for q, mass_q in question.items()
        for s, mass_s in slant.items()
        for n, mass_n in noise.items()
    )


def expected_question_score(scenario: Scenario, model: ModelId, stance: int) -> float:
    """The model's expected score on a question of the given stance: the mean over the two statements."""
    spread = model_spread(scenario, model)
    question = convolve(integer_pmf(shared_question_sd(scenario)), integer_pmf(own_question_sd(scenario, model)))
    slant = integer_pmf(scenario.statement_sd * spread)
    noise = integer_pmf(scenario.repetition_sd * spread)
    return fmean(
        expected_answer_value(stance, polarity, statement_lean(scenario, polarity), question, slant, noise)
        for polarity in Polarity
    )


def facet_weights(scenario: Scenario) -> dict[str, float]:
    """Each facet's share of an axis's questions, as the questionnaire assigns them in turn."""
    questionnaire = audit_questionnaire(scenario.questions_per_axis, facet_count(scenario))
    on_axis = [question.facet for question in questionnaire.questions if question.axis is AxisKey.X]
    return {facet: on_axis.count(facet) / len(on_axis) for facet in dict.fromkeys(on_axis)}


def shift_share(scenario: Scenario, model: ModelId) -> float:
    return scenario.second_shift_share if model == MODELS[1] else 0.0


def population_position(scenario: Scenario, model: ModelId) -> float:
    """The model's expected question score on either axis, exactly, from the integer effects and the clamping.

    The wording shifts and the first-option lean are left out: the shifts are what the interval does not cover, and
    the lean cancels by the symmetry of the four layouts. A uniform responder sits at 0."""
    if scenario.noise is NoiseKind.UNIFORM:
        return 0.0
    share = shift_share(scenario, model)
    expected = sum(
        weight
        * (
            (1 - share) * expected_question_score(scenario, model, scenario.position_points + offset)
            + share * expected_question_score(scenario, model, scenario.position_points + offset + 1)
        )
        for facet, weight in facet_weights(scenario).items()
        for offset in (facet_offsets(scenario)[facet],)
    )
    # a symmetric population sums to 0 up to rounding; a point interval at 0 must still cover it
    return round(expected, POSITION_DECIMALS)


def stance_position(scenario: Scenario, model: ModelId) -> float:
    """What the model's stance would read as in score units with no clamping and no lean: its points times one
    point's score, averaged over the facets."""
    if scenario.noise is NoiseKind.UNIFORM:
        return 0.0
    mean_offset = sum(weight * facet_offsets(scenario)[facet] for facet, weight in facet_weights(scenario).items())
    return (scenario.position_points + mean_offset + shift_share(scenario, model)) * POINT_SCORE


def model_positions(scores: Sequence[QuestionScore]) -> AxisPair[AxisPosition]:
    """Both axes at full coverage, so only the intervals and the question counts gate a claim."""
    return AxisPair(
        x=axis_position(scores, AxisKey.X, 1.0, SETTINGS), y=axis_position(scores, AxisKey.Y, 1.0, SETTINGS)
    )


def covers(position: AxisPosition, target: float) -> bool:
    estimate = position.estimate
    return isinstance(estimate, Bounded) and estimate.low <= target <= estimate.high


def misses_below(position: AxisPosition, target: float) -> bool:
    estimate = position.estimate
    return isinstance(estimate, Bounded) and estimate.high < target


def misses_above(position: AxisPosition, target: float) -> bool:
    estimate = position.estimate
    return isinstance(estimate, Bounded) and estimate.low > target


def is_extreme(record: TrialRecord) -> bool:
    """The record's rating sits at either end of the scale."""
    match record.outcome:
        case Replied(reading=RatingRead(canonical=rating)):
            return rating in (1, len(LABELS))
        case _:
            return False


def covered_share(positions: Mapping[ModelId, AxisPair[AxisPosition]], targets: Mapping[ModelId, float]) -> float:
    """The share of models whose two intervals both cover the model's target."""
    return fmean(
        covers(positions[model].x, targets[model]) and covers(positions[model].y, targets[model]) for model in MODELS
    )


def run_errors(scenario: Scenario, seed: int) -> RunOutcome:
    questionnaire = audit_questionnaire(scenario.questions_per_axis, facet_count(scenario))
    records = simulate_records(scenario, seed)
    values = phrasing_values(records, questionnaire.scale)
    scores = question_scores(values, questionnaire, MODELS)
    positions = {model: model_positions(scores[model]) for model in MODELS}
    populations = {model: population_position(scenario, model) for model in MODELS}
    stances = {model: stance_position(scenario, model) for model in MODELS}
    pairs = pair_axes(scores, SETTINGS)
    orderings = [
        ordering_claims(pair, first, positions[first], second, positions[second], SETTINGS, pending=0)
        for (first, second), pair in pairs.items()
    ]
    equivalences = [
        equivalence_claims(pair, first, positions[first], second, positions[second], SETTINGS, pending=0)
        for (first, second), pair in pairs.items()
    ]
    return RunOutcome(
        covered=covered_share(positions, populations),
        stance_covered=covered_share(positions, stances),
        misses_below=sum(
            misses_below(positions[model].get(axis), populations[model]) for model in MODELS for axis in AxisKey
        ),
        misses_above=sum(
            misses_above(positions[model].get(axis), populations[model]) for model in MODELS for axis in AxisKey
        ),
        ordering_asserted=any(isinstance(claim, Asserted) for pair in orderings for claim in (pair.x, pair.y)),
        equivalence_asserted=any(isinstance(claim, Asserted) for pair in equivalences for claim in (pair.x, pair.y)),
        extreme_ratings=sum(is_extreme(record) for record in records),
        ratings=len(records),
    )


def wilson_interval(successes: int, trials: int) -> tuple[float, float]:
    """The 95% Wilson score interval of a binomial proportion."""
    share = successes / trials
    denominator = 1 + INTERVAL_Z**2 / trials
    middle = (share + INTERVAL_Z**2 / (2 * trials)) / denominator
    half_width = INTERVAL_Z * math.sqrt(share * (1 - share) / trials + INTERVAL_Z**2 / (4 * trials**2)) / denominator
    return max(0.0, middle - half_width), min(1.0, middle + half_width)


def monte_carlo_error(successes: int, trials: int) -> float:
    """The standard error of an estimated proportion over `trials` independent simulated draws."""
    share = successes / trials
    return math.sqrt(share * (1 - share) / trials)


def share_statistics(shares: Sequence[float]) -> tuple[float, tuple[float, float], float]:
    """The mean of per-run shares, its 95% normal interval, and its Monte Carlo error from the shares' spread.

    The run is the unit, so two models whose misses are correlated within a run do not count as independent."""
    mean = fmean(shares)
    error = stdev(shares) / math.sqrt(len(shares)) if len(shares) >= 2 else 0.0
    return mean, (max(0.0, mean - INTERVAL_Z * error), min(1.0, mean + INTERVAL_Z * error)), error


def rate_statistics(successes: int, runs: int) -> tuple[float, tuple[float, float], float]:
    """A per-run binary rate with its Wilson interval and binomial error."""
    return successes / runs, wilson_interval(successes, runs), monte_carlo_error(successes, runs)


def run_scenario(scenario: Scenario, runs: int, seed: int, provenance: Provenance) -> ScenarioResult:
    """Run i uses seed + i. Coverage averages per-run shares of models; the two claim rates count runs."""
    outcomes = [run_errors(scenario, seed + index) for index in range(runs)]
    coverage, coverage_interval, coverage_mcse = share_statistics([outcome.covered for outcome in outcomes])
    stance_coverage, stance_interval, stance_mcse = share_statistics([outcome.stance_covered for outcome in outcomes])
    ordering_rate, ordering_interval, ordering_mcse = rate_statistics(
        sum(outcome.ordering_asserted for outcome in outcomes), runs
    )
    equivalence_rate, equivalence_interval, equivalence_mcse = rate_statistics(
        sum(outcome.equivalence_asserted for outcome in outcomes), runs
    )
    population = population_position(scenario, MODELS[0])
    stance = stance_position(scenario, MODELS[0])
    return ScenarioResult(
        scenario=scenario,
        runs=runs,
        seed=seed,
        population_position=population,
        second_population_position=population_position(scenario, MODELS[1]),
        stance=stance,
        second_stance=stance_position(scenario, MODELS[1]),
        bias=population - stance,
        coverage=coverage,
        coverage_interval=coverage_interval,
        coverage_mcse=coverage_mcse,
        stance_coverage=stance_coverage,
        stance_coverage_interval=stance_interval,
        stance_coverage_mcse=stance_mcse,
        misses_below=sum(outcome.misses_below for outcome in outcomes),
        misses_above=sum(outcome.misses_above for outcome in outcomes),
        ordering_rate=ordering_rate,
        ordering_interval=ordering_interval,
        ordering_mcse=ordering_mcse,
        equivalence_rate=equivalence_rate,
        equivalence_interval=equivalence_interval,
        equivalence_mcse=equivalence_mcse,
        extreme_share=sum(outcome.extreme_ratings for outcome in outcomes)
        / sum(outcome.ratings for outcome in outcomes),
        version=VERSION,
        code_revision=provenance.code_revision,
        command=provenance.command,
    )


def run_job(job: tuple[Scenario, int, int], provenance: Provenance) -> ScenarioResult:
    scenario, runs, seed = job
    return run_scenario(scenario, runs, seed, provenance)


def run_jobs(
    jobs: Sequence[tuple[Scenario, int, int]], provenance: Provenance, workers: int
) -> tuple[ScenarioResult, ...]:
    """Each job's scenario run with its runs and seed, `workers` scenarios at a time, in the jobs' order."""
    if workers <= 1:
        return tuple(run_job(job, provenance) for job in jobs)
    with ProcessPoolExecutor(max_workers=workers) as executor:
        return tuple(executor.map(partial(run_job, provenance=provenance), jobs))


def run_audit(arguments: AuditArguments, provenance: Provenance) -> tuple[ScenarioResult, ...]:
    jobs = [(scenario, arguments.runs, arguments.seed) for scenario in scenarios()]
    return run_jobs(jobs, provenance, arguments.workers)


def write_results(results: Sequence[ScenarioResult], path: Path) -> None:
    document = {"$comment": GENERATED_COMMENT, "results": [result.model_dump(mode="json") for result in results]}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    return


def load_results(path: Path) -> tuple[ScenarioResult, ...]:
    """The results write_results wrote, validated in JSON mode as every stored document is."""
    document = json.loads(path.read_text(encoding="utf-8"))
    return tuple(ScenarioResult.model_validate_json(json.dumps(row)) for row in document["results"])


def rate_text(rate: float, mcse: float) -> str:
    """A rate as the calibration table prints it: `0.945 ± 0.002`."""
    return f"{rate:.3f} ± {mcse:.3f}"


def table_row(result: ScenarioResult) -> str:
    """One row of METHODOLOGY's calibration table, in its column order."""
    cells = (
        result.scenario.name,
        str(result.scenario.questions_per_axis),
        f"{result.stance:+.2f}",
        rate_text(result.coverage, result.coverage_mcse),
        rate_text(result.stance_coverage, result.stance_coverage_mcse),
        rate_text(result.ordering_rate, result.ordering_mcse),
        rate_text(result.equivalence_rate, result.equivalence_mcse),
        f"{result.bias:+.3f}",
        f"{result.extreme_share:.2f}",
    )
    return f"| {' | '.join(cells)} |"


def rates_agree(stored: ScenarioResult, rerun: ScenarioResult) -> bool:
    """Each audited rate lies within CHECK_TOLERANCE combined Monte Carlo errors of the stored one.

    A full re-run with the stored seed and runs is deterministic, so any difference is a changed simulator; a
    capped re-run differs by its own sampling noise, which the combined error allows for. One run's share of the
    re-run joins the error, since a rate that came out 0 or 1 in every re-run has no spread to estimate it from."""
    resolution = 1 / rerun.runs
    rates = (
        (stored.coverage, stored.coverage_mcse, rerun.coverage, rerun.coverage_mcse),
        (stored.stance_coverage, stored.stance_coverage_mcse, rerun.stance_coverage, rerun.stance_coverage_mcse),
        (stored.ordering_rate, stored.ordering_mcse, rerun.ordering_rate, rerun.ordering_mcse),
        (stored.equivalence_rate, stored.equivalence_mcse, rerun.equivalence_rate, rerun.equivalence_mcse),
    )
    return all(
        abs(was - now) <= CHECK_TOLERANCE * math.hypot(was_error, now_error, resolution)
        for was, was_error, now, now_error in rates
    )


def check_results(
    stored: Sequence[ScenarioResult], check_runs: int | None, provenance: Provenance, workers: int = 1
) -> tuple[str, ...]:
    """Each stored scenario re-run with its seed and runs (capped at `check_runs`); the names that disagree."""
    jobs = [
        (result.scenario, result.runs if check_runs is None else min(result.runs, check_runs), result.seed)
        for result in stored
    ]
    reruns = run_jobs(jobs, provenance, workers)
    return tuple(
        f"{result.scenario.name}: coverage {result.coverage:.4f} now {rerun.coverage:.4f}, "
        f"orderings {result.ordering_rate:.4f} now {rerun.ordering_rate:.4f}, "
        f"equivalences {result.equivalence_rate:.4f} now {rerun.equivalence_rate:.4f}"
        for result, rerun in zip(stored, reruns, strict=True)
        if not rates_agree(result, rerun)
    )


def main() -> None:
    arguments = parse_arguments(sys.argv[1:])
    provenance = audit_provenance(os.environ, sys.argv)
    if arguments.table is not None:
        for result in load_results(arguments.table):
            print(table_row(result))
        return
    if arguments.check is not None:
        disagreeing = check_results(load_results(arguments.check), arguments.check_runs, provenance, arguments.workers)
        for line in disagreeing:
            print(line, file=sys.stderr)
        sys.exit(1 if disagreeing else 0)
    results = run_audit(arguments, provenance)
    write_results(results, arguments.out)
    return


if __name__ == "__main__":
    main()
