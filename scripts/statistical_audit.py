@dataclass(frozen=True)
class AuditArguments:
    """`check` names a results file to re-run and compare instead of writing `out`; `check_runs` caps each
    scenario's runs for a quick check, at the cost of a wider tolerance; `table` prints a stored file's rows as
    METHODOLOGY's calibration table shows them."""

    runs: int
    seed: int
    out: Path
    check: Path | None
    check_runs: int | None
    table: Path | None
    workers: int


@dataclass(frozen=True)
class Provenance:
    code_revision: str
    command: str


def parse_arguments(argv: Sequence[str]) -> AuditArguments:
    parser = argparse.ArgumentParser(description="Audit interval coverage and the pair tests' error rates.")
    parser.add_argument("--runs", type=int, default=1000, help="simulated runs per scenario")
    parser.add_argument("--seed", type=int, default=0, help="the first run's seed; run i uses seed + i")
    parser.add_argument(
        "--out", type=Path, default=REPOSITORY / "audits" / "statistical-audit.json", help="the results file"
    )
    parser.add_argument("--check", type=Path, default=None, help="re-run a results file's scenarios and compare")
    parser.add_argument("--check-runs", type=int, default=None, help="cap each scenario's runs during --check")
    parser.add_argument("--table", type=Path, default=None, help="print a results file as the calibration table")
    parser.add_argument("--workers", type=int, default=os.cpu_count() or 1, help="scenarios run at once")
    arguments = parser.parse_args(argv)
    return AuditArguments(
        runs=arguments.runs,
        seed=arguments.seed,
        out=arguments.out,
        check=arguments.check,
        check_runs=arguments.check_runs,
        table=arguments.table,
        workers=arguments.workers,
    )


def audit_provenance(environ: Mapping[str, str], argv: Sequence[str]) -> Provenance:
    return Provenance(code_revision=code_revision(environ), command=" ".join(argv))


