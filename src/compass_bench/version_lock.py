"""The version lock: every locked component's digest under the current VERSION, recorded in version.lock.json.

The components are the report and pooled report schemas, each example report (the analysis's output on the
synthetic runs), and each bundled data file: the catalog, the experiments, and the questionnaires. A data file is
hashed as the JSON it parses to, so an edit to a comment or the layout is not a change. scripts/update_lock.py records
the lock, and
tests/test_version_lock.py fails when a digest changes while VERSION stays the locked version. Once VERSION is the
next version, its components may change until make lock records them.
"""

import json
from collections.abc import Mapping, Sequence
from pathlib import Path, PurePath
from typing import Final

from pydantic import Field

from compass_bench.adapters.files.source_files import SourceFiles
from compass_bench.contract.schema import example_digests, pooled_report_schema, report_schema
from compass_bench.domain.ids import content_hash
from compass_bench.domain.value import Value
from compass_bench.version import VERSION

DATA_DIRECTORY: Final = Path(__file__).parent / "data"
DATA_SUFFIXES: Final = (".yaml", ".json")
GENERATED_COMMENT: Final = "Generated by scripts/update_lock.py. Do not edit."


class VersionLock(Value):
    """The version the digests were recorded under, and each component's digest by name."""

    comment: str = Field(alias="$comment")
    version: str
    digests: dict[str, str]


def data_paths(directory: Path) -> tuple[PurePath, ...]:
    """Every YAML and JSON file under `directory`, relative to it, sorted."""
    return tuple(sorted(path.relative_to(directory) for path in directory.rglob("*") if path.suffix in DATA_SUFFIXES))


def data_digest(files: SourceFiles, path: PurePath) -> str:
    text = files.read_yaml(path) if path.suffix == ".yaml" else files.read_json(path)
    return content_hash(json.loads(text))


def component_digests() -> dict[str, str]:
    """Each locked component's digest, keyed by its name."""
    files = SourceFiles(DATA_DIRECTORY)
    return {
        "report schema": content_hash(report_schema()),
        "pooled report schema": content_hash(pooled_report_schema()),
        **{f"example report {name}": digest for name, digest in example_digests().items()},
        **{f"data/{path}": data_digest(files, path) for path in data_paths(DATA_DIRECTORY)},
    }


def current_lock() -> VersionLock:
    return VersionLock.model_validate(
        {"$comment": GENERATED_COMMENT, "version": VERSION, "digests": component_digests()}
    )


def changed_components(recorded: Mapping[str, str], current: Mapping[str, str]) -> tuple[str, ...]:
    """The components added, removed, or holding a different digest, by name."""
    return tuple(sorted(name for name in recorded.keys() | current.keys() if recorded.get(name) != current.get(name)))


def next_version(version: str) -> str:
    """The next minor version: 2.1 gives 2.2."""
    major, minor = version.split(".")
    return f"{major}.{int(minor) + 1}"


def bump_message(version: str, changed: Sequence[str]) -> str:
    return (
        f"changed under version {version}: {', '.join(changed)}; "
        f"set VERSION to {next_version(version)} in src/compass_bench/version.py, and run make lock when it is done"
    )


def lock_problem(recorded: VersionLock, current: VersionLock) -> str | None:
    """Why the current state breaks the lock, or None.

    Under the recorded version no component may change; the next version may change any until make lock records it."""
    following = next_version(recorded.version)
    if current.version == following:
        return None
    if current.version != recorded.version:
        return f"VERSION {current.version} is neither the locked {recorded.version} nor the next, {following}"
    changed = changed_components(recorded.digests, current.digests)
    return bump_message(current.version, changed) if changed else None
